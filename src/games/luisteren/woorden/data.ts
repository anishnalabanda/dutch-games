export const words: ListenWord[] = THEMES.flatMap((theme) =>
  ENTRIES[theme.id].map(([nl, en, pair]) => ({ id: `${theme.id}:${nl}`, theme: theme.id, nl, en, pair })),
)

/** One stable array per theme: `useDrill` needs the same reference on every render. */
export const wordsByTheme = Object.fromEntries(
  THEMES.map((theme) => [theme.id, words.filter((w) => w.theme === theme.id)]),
) as Record<ThemeId, ListenWord[]>

export const STORE_PREFIX = 'nl.luisteren.woorden-'

export function themeFromKey(key: string): ThemeId | null {
  const id = key.startsWith(STORE_PREFIX) ? key.slice(STORE_PREFIX.length) : ''
  return THEMES.some((t) => t.id === id) ? (id as ThemeId) : null
}

/** What a meaning looks like, so wrong options can't be ruled out by form alone. */
function shape(en: string): string {
  if (/^[€\d]/.test(en)) return 'number'
  if (en.startsWith('to ')) return 'verb'
  if (en.startsWith('the ')) return 'noun'
  return 'other'
}

/**
 * Four meanings to choose from: the right one, the easily confused pair when
 * there is one (in either direction), then others of the same shape, then any.
 */
export function optionsFor(word: ListenWord, pool: ListenWord[]): string[] {
  const others = pool.filter((w) => w.id !== word.id && w.en !== word.en)
  const pair = others.filter((w) => w.nl === word.pair || w.pair === word.nl)
  const rest = others.filter((w) => !pair.includes(w))
  const random = shuffle(rest)
  const sameShape = random.filter((w) => shape(w.en) === shape(word.en))
  const picked: string[] = []
  for (const w of [...pair, ...sameShape, ...random]) {
    if (picked.length === 3) break
    if (!picked.includes(w.en)) picked.push(w.en)
  }
  return shuffle([word.en, ...picked])
}
