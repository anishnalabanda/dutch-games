/**
 * The words that keep coming back in A2 listening: the questions on screen, days
 * and times, numbers and prices, and the everyday situations the dialogues are
 * set in. DUO publishes no official word list, so this is a common A2 core per
 * theme, not a copy of the exam. Each theme is its own game.
 *
 * Every word on the screens of DUO oefenexamen Luisteren 2 (questions, options,
 * situation lines, the start and end screens) is in here as a word or a short
 * phrase, not as the exam's sentences: prepositions, pronouns and verb forms
 * have their own themes because the questions are built from them.
 *
 * A word is written `[dutch, english]`, or `[dutch, english, pair]` where `pair`
 * is the Dutch of a word in the same theme it is easily confused with by ear
 * (dertien / dertig, al / pas). The drill then always offers the pair's meaning
 * as one of the wrong options, in both directions.
 */
import { shuffle } from '../../normalize'

export type ThemeId =
  | 'vragen'
  | 'tijd'
  | 'getallen'
  | 'kleinewoorden'
  | 'voorzetsels'
  | 'verwijswoorden'
  | 'werkwoorden'
  | 'gezondheid'
  | 'werk'
  | 'wonen'
  | 'school'
  | 'winkelen'
  | 'reizen'
  | 'route'
  | 'instanties'
  | 'vrijetijd'

export interface Theme {
  id: ThemeId
  /** Dutch: the game title. */
  title: string
  /** English: the game's subtitle and hover gloss. */
  subtitle: string
}

export interface ListenWord {
  /** Stable: theme plus the Dutch, so reordering the list keeps saved progress. */
  id: string
  theme: ThemeId
  nl: string
  en: string
  /** The Dutch of an easily confused word in the same theme. */
  pair?: string
}

type Entry = [nl: string, en: string, pair?: string]

